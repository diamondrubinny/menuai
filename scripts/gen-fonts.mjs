// Generates src/core/fontFiles.generated.ts from the installed @fontsource packages.
// Run: node scripts/gen-fonts.mjs  (re-run after adding a family to FAMILIES)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FAMILIES = [
  'heebo', 'rubik', 'frank-ruhl-libre', 'suez-one', 'secular-one', 'amatic-sc',
  'playfair-display', 'cormorant-garamond', 'cairo', 'amiri', 'bebas-neue', 'inter',
];
const WEIGHTS = [400, 700];
const SUBSETS = ['latin', 'latin-ext', 'hebrew', 'arabic', 'cyrillic', 'cyrillic-ext', 'greek', 'vietnamese'];

const imports = [];
const entries = [];
let n = 0;
for (const family of FAMILIES) {
  for (const weight of WEIGHTS) {
    const cssPath = `node_modules/@fontsource/${family}/${weight}.css`;
    if (!existsSync(cssPath)) continue;
    const css = readFileSync(cssPath, 'utf8');
    const blocks = css.split('@font-face').slice(1);
    for (const block of blocks) {
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!range || !file) continue;
      const subset = file.replace(`${family}-`, '').replace(`-${weight}-normal.woff2`, '');
      if (!SUBSETS.includes(subset)) continue;
      const id = `f${n++}`;
      imports.push(`import ${id} from '@fontsource/${family}/files/${file}?url';`);
      entries.push(`  { family: '${family}', weight: ${weight}, subset: '${subset}', unicodeRange: '${range.trim()}', url: ${id} },`);
    }
  }
}

const out = `/*! @license
 * MenuAI — open-source menu builder · https://github.com/diamondrubinny/menuai
 * Copyright (c) 2026 Diamond Rubinny and MenuAI contributors · AGPL-3.0-only + attribution terms (NOTICE)
 * Powered by MenuAI. This notice must be kept (see LICENSE and NOTICE).
 */
// AUTO-GENERATED by scripts/gen-fonts.mjs — do not edit by hand.
${imports.join('\n')}

export interface FontFile {
  family: string;
  weight: number;
  subset: string;
  unicodeRange: string;
  url: string;
}

export const FONT_FILES: FontFile[] = [
${entries.join('\n')}
];
`;
writeFileSync('src/core/fontFiles.generated.ts', out);
console.log(`Wrote ${entries.length} font files.`);
