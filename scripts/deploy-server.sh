# Powered by MenuAI. This notice must be kept (see LICENSE and NOTICE).
#
# Installs or updates the full MenuAI stack (editor + API + PostgreSQL + ClamAV) on Ubuntu 22.04/24.04,
# behind nginx with HTTPS (Let's Encrypt). Re-run the same command to update; data and .env are kept.
#
# Usage (on the server, as root):
#   DOMAIN=menu.example.com EMAIL=you@example.com OWNER_EMAIL=you@example.com bash scripts/deploy-server.sh
# Over SSH, straight from GitHub:
#   ssh root@server 'curl -fsSL https://raw.githubusercontent.com/diamondrubinny/menuai/main/scripts/deploy-server.sh \
#     | DOMAIN=menu.example.com EMAIL=you@example.com OWNER_EMAIL=you@example.com bash'
#
# Env: DOMAIN (required), EMAIL (Let's Encrypt; required unless SKIP_TLS=1 and you terminate TLS yourself),
#      OWNER_EMAIL (create the first owner), BACKUP_AGE_RECIPIENT (age1… public key: daily encrypted backups),
#      BRANCH (main), REPO, APP_DIR (/opt/menuai), WEB_ROOT (/var/www/menuai)
# Review only: bash scripts/deploy-server.sh --render-nginx <dir>   writes the nginx files to <dir> and exits.
set -euo pipefail

DOMAIN="${DOMAIN:-}"
EMAIL="${EMAIL:-}"
OWNER_EMAIL="${OWNER_EMAIL:-}"
BACKUP_AGE_RECIPIENT="${BACKUP_AGE_RECIPIENT:-}"
SKIP_TLS="${SKIP_TLS:-0}"
BRANCH="${BRANCH:-main}"
REPO="${REPO:-https://github.com/diamondrubinny/menuai.git}"
APP_DIR="${APP_DIR:-/opt/menuai}"
WEB_ROOT="${WEB_ROOT:-/var/www/menuai}"

die() { echo "deploy: $*" >&2; exit 1; }
step() { echo "==> $*"; }

# --- nginx configuration ------------------------------------------------------------------------
# Security headers apply to the static editor only. Published menus (/m/), images (/media/) and the
# API set their own, stricter headers: a second CSP from nginx would be enforced too and break them.
render_nginx() {
  local out="$1" tls="$2"
  mkdir -p "$out/conf.d" "$out/snippets" "$out/sites-available"

  cat > "$out/conf.d/menuai-privacy-log.conf" <<'NGINX'
# MenuAI: privacy-friendly access log — IPv4 last octet / IPv6 last 80 bits removed, path without query string.
map $remote_addr $menuai_ip {
    ~^(?P<a>\d+\.\d+\.\d+)\.\d+$          $a.0;
    ~^(?P<b>[0-9a-fA-F]*:[0-9a-fA-F]*:[0-9a-fA-F]*):  $b::;
    default                                 -;
}
log_format menuai_privacy '$menuai_ip [$time_local] "$request_method $uri $server_protocol" $status $body_bytes_sent';
NGINX

  {
    echo '# MenuAI editor security headers (static files only).'
    echo 'add_header X-Content-Type-Options "nosniff" always;'
    echo 'add_header X-Frame-Options "DENY" always;'
    echo 'add_header Referrer-Policy "strict-origin-when-cross-origin" always;'
    echo 'add_header Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=()" always;'
    echo 'add_header Cross-Origin-Opener-Policy "same-origin" always;'
    echo "add_header Content-Security-Policy \"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https:; font-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'\" always;"
    if [[ "$tls" == 1 ]]; then echo 'add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;'; fi
  } > "$out/snippets/menuai-security.conf"

  cat > "$out/snippets/menuai-proxy.conf" <<'NGINX'
# MenuAI API proxy (exactly one trusted hop: the API trusts X-Forwarded-For from nginx only).
proxy_pass http://127.0.0.1:3000;
proxy_http_version 1.1;
proxy_set_header Host $host;
proxy_set_header X-Forwarded-For $remote_addr;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_read_timeout 60s;
NGINX

  cat > "$out/sites-available/menuai" <<NGINX
# MenuAI site — generated by scripts/deploy-server.sh (re-running the script rewrites this file).
server {
    listen 80;
    listen [::]:80;
    server_name $DOMAIN;
    root $WEB_ROOT;
    index index.html;
    server_tokens off;
    access_log /var/log/nginx/menuai.access.log menuai_privacy;
    client_max_body_size 1m;

    location /api/ {
        # Menus may embed images; uploads are capped at 8 MB by the API.
        client_max_body_size 12m;
        include snippets/menuai-proxy.conf;
    }
    location /m/ {
        include snippets/menuai-proxy.conf;
    }
    location /media/ {
        include snippets/menuai-proxy.conf;
    }
    location /assets/ {
        include snippets/menuai-security.conf;
        expires 1y;
    }
    location / {
        include snippets/menuai-security.conf;
        try_files \$uri \$uri/ /index.html;
        expires -1;
    }
}
NGINX
}

if [[ "${1:-}" == "--render-nginx" ]]; then
  [[ -n "${2:-}" ]] || die "usage: --render-nginx <dir>"
  DOMAIN="${DOMAIN:-menu.example.com}"
  render_nginx "$2" "${TLS:-1}"
  echo "nginx files written to $2"
  exit 0
fi

# --- checks ---------------------------------------------------------------------------------------
[[ $EUID -eq 0 ]] || die "run as root (sudo)."
[[ "$DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]] || die "set DOMAIN, e.g. DOMAIN=menu.example.com"
email_re='^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
if [[ "$SKIP_TLS" != 1 ]]; then [[ "$EMAIL" =~ $email_re ]] || die "set EMAIL for Let's Encrypt (or SKIP_TLS=1 if you terminate HTTPS yourself)"; fi
[[ -z "$OWNER_EMAIL" || "$OWNER_EMAIL" =~ $email_re ]] || die "OWNER_EMAIL is not a valid address"
[[ -z "$BACKUP_AGE_RECIPIENT" || "$BACKUP_AGE_RECIPIENT" =~ ^age1[02-9ac-hj-np-z]{58}$ ]] || die "BACKUP_AGE_RECIPIENT must be an age public key (age1...)"
# shellcheck disable=SC1091
. /etc/os-release
[[ "${ID:-}" == ubuntu ]] || echo "deploy: warning: tested on Ubuntu 22.04/24.04 (this is ${PRETTY_NAME:-unknown})." >&2

# --- packages -------------------------------------------------------------------------------------
step "Installing system packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq git nginx rsync ca-certificates curl openssl age docker.io docker-compose-v2 >/dev/null
systemctl enable --now docker >/dev/null
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is missing (install Docker from docker.com, then re-run)."
if ! command -v node >/dev/null || [[ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]]; then
  step "Installing Node.js 22 (NodeSource) to build the editor"
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null
  apt-get install -y -qq nodejs >/dev/null
fi
mem_mb=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
(( mem_mb >= 2500 )) || echo "deploy: warning: ${mem_mb} MB RAM; PostgreSQL + API + ClamAV need about 2.5 GB." >&2

# --- source and editor ----------------------------------------------------------------------------
step "Fetching source ($BRANCH)"
if [[ -d "$APP_DIR/.git" ]]; then
  git -C "$APP_DIR" fetch --quiet origin "$BRANCH"
  git -C "$APP_DIR" checkout --quiet "$BRANCH"
  git -C "$APP_DIR" reset --quiet --hard "origin/$BRANCH"
else
  git clone --quiet --branch "$BRANCH" "$REPO" "$APP_DIR"
fi
cd "$APP_DIR"

step "Building the editor"
npm ci --no-audit --no-fund --loglevel=error
# Separate lines: under `set -e` a failure on the left of `&&` would not stop the script.
npx tsc -p .
npx vite build --logLevel warn
mkdir -p "$WEB_ROOT"
rsync -a --delete dist/ "$WEB_ROOT/"
chown -R www-data:www-data "$WEB_ROOT"

# --- configuration (never overwritten) ------------------------------------------------------------
if [[ ! -f .env ]]; then
  step "Creating .env with a random database password"
  umask 077
  cat > .env <<ENV
# Generated by scripts/deploy-server.sh — keep this file private (it is not in git).
PUBLIC_URL=https://$DOMAIN
POSTGRES_PASSWORD=$(openssl rand -hex 24)
# Email for sign-in links: any SMTP provider, e.g. smtps://user:password@smtp.example.com:465
SMTP_URL=
MAIL_FROM="MenuAI <menu@$DOMAIN>"
LOG_LEVEL=info
UPLOAD_QUOTA_MB=2048
ENV
  umask 022
fi
chmod 600 .env

# --- containers -----------------------------------------------------------------------------------
step "Starting PostgreSQL, ClamAV and the API (first start downloads virus signatures: a few minutes)"
docker compose up -d --build --wait --wait-timeout 900

# --- nginx and HTTPS ------------------------------------------------------------------------------
step "Configuring nginx for $DOMAIN"
tls=0
if [[ "$SKIP_TLS" != 1 && -d "/etc/letsencrypt/live/$DOMAIN" ]]; then tls=1; fi
render_nginx /etc/nginx "$tls"
ln -sf /etc/nginx/sites-available/menuai /etc/nginx/sites-enabled/menuai
nginx -t
systemctl reload nginx

if [[ "$SKIP_TLS" != 1 ]]; then
  step "Enabling HTTPS (Let's Encrypt)"
  apt-get install -y -qq certbot python3-certbot-nginx >/dev/null
  certbot --nginx --non-interactive --agree-tos --keep-until-expiring --redirect -m "$EMAIL" -d "$DOMAIN"
  # HSTS only once HTTPS works.
  render_nginx /tmp/menuai-nginx-tls 1
  cp /tmp/menuai-nginx-tls/snippets/menuai-security.conf /etc/nginx/snippets/menuai-security.conf
  rm -rf /tmp/menuai-nginx-tls
  nginx -t
  systemctl reload nginx
fi

# --- daily encrypted backups ----------------------------------------------------------------------
if [[ -n "$BACKUP_AGE_RECIPIENT" ]]; then
  step "Scheduling daily encrypted backups (03:17)"
  echo "$BACKUP_AGE_RECIPIENT" > "$APP_DIR/.backup-recipient"
  cat > /etc/systemd/system/menuai-backup.service <<UNIT
[Unit]
Description=MenuAI encrypted backup
After=docker.service

[Service]
Type=oneshot
Environment=APP_DIR=$APP_DIR
ExecStart=/bin/bash $APP_DIR/scripts/backup.sh
UNIT
  cat > /etc/systemd/system/menuai-backup.timer <<UNIT
[Unit]
Description=Daily MenuAI encrypted backup

[Timer]
OnCalendar=*-*-* 03:17:00
Persistent=true

[Install]
WantedBy=timers.target
UNIT
  systemctl daemon-reload
  systemctl enable --now menuai-backup.timer >/dev/null
fi

# --- first owner and status -----------------------------------------------------------------------
if [[ -n "$OWNER_EMAIL" ]]; then
  step "Creating the first owner"
  docker compose exec -T api node dist-server/cli.mjs create-owner "$OWNER_EMAIL" || \
    docker compose exec -T api node dist-server/cli.mjs login-link "$OWNER_EMAIL" || true
fi

step "Status"
docker compose exec -T api node dist-server/cli.mjs status || true

scheme=https; [[ "$SKIP_TLS" == 1 ]] && scheme="https (your TLS)"
cat <<DONE

==> Done: $scheme://$DOMAIN
    Sign-in link for another user:   cd $APP_DIR && docker compose exec api node dist-server/cli.mjs login-link <email>
    Health:                           cd $APP_DIR && docker compose exec api node dist-server/cli.mjs status
    Backups:                          ${BACKUP_AGE_RECIPIENT:+daily at 03:17 in /var/backups/menuai (copy them off the server)}${BACKUP_AGE_RECIPIENT:-not scheduled — set BACKUP_AGE_RECIPIENT (see docs/PHASE2F.md)}
    Email:                            set SMTP_URL in $APP_DIR/.env, then: docker compose up -d
DONE
