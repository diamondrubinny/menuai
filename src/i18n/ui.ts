export const UI_DICTS: Record<string, Dict> = { he, en, ar };
export const UI_LANGS = [
  { code: 'he', name: 'עברית', dir: 'rtl' as const },
  { code: 'en', name: 'English', dir: 'ltr' as const },
  { code: 'ar', name: 'العربية', dir: 'rtl' as const },
];

function detectUiLang(): string {
  const saved = loadPrefs().uiLang;
  if (saved && UI_DICTS[saved]) return saved;
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const base = l.toLowerCase().split('-')[0]!;
    if (UI_DICTS[base]) return base;
  }
  return 'he';
}

interface UiState {
  lang: string;
  setLang: (lang: string) => void;
}

export const useUiLang = create<UiState>((set) => ({
  lang: detectUiLang(),
  setLang: (lang) => {
    if (!UI_DICTS[lang]) return;
    savePrefs({ uiLang: lang });
    set({ lang });
  },
}));

export type Translate = (key: UiKey, vars?: Record<string, string | number>) => string;

export function translate(lang: string, key: UiKey, vars?: Record<string, string | number>): string {
  const text = (UI_DICTS[lang] ?? en)[key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : text;
}

export function useT(): { t: Translate; lang: string; dir: 'ltr' | 'rtl' } {
  const lang = useUiLang((s) => s.lang);
  const dir = UI_LANGS.find((l) => l.code === lang)?.dir ?? 'ltr';
  return { t: (key, vars) => translate(lang, key, vars), lang, dir };
}
